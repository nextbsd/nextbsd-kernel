#!/bin/sh
#
# smoke-overlay.sh -- the nextbsd-ci manifest overlay for the kernel smoke test.
#
# The smoke test boots the image with one on-image suite, ci/zfs-smoke.sh
# (/usr/tests/nextbsd-kernel/zfs-smoke.sh). The harness treats an unknown
# suite as owning every marker, so its absence check would require every
# must-pass marker of the userland suites, which this image never runs. This
# writes an overlay (nextbsd-ci manifest schema) that:
#   - turns every must-pass / fail-gates row of the base table and of
#     overlay-nextbsd-kernel.tsv into warn: not this suite's markers, and
#   - adds the ZFS-* markers zfs-smoke.sh prints as must-pass.
# Generated from the pinned nextbsd-ci checkout, so a marker added there later
# is covered without a change here.
#
# usage: smoke-overlay.sh <nextbsd-ci checkout> <out.tsv>
#
set -eu

USAGE="usage: smoke-overlay.sh <nextbsd-ci checkout> <out.tsv>"
CI=${1:?$USAGE}
OUT=${2:?$USAGE}
M="$CI/manifest"
[ -f "$M/markers.tsv" ] || { echo "smoke-overlay: no $M/markers.tsv" >&2; exit 1; }

T=$(printf '\t')
{
	echo "# generated by nextbsd-kernel ci/smoke-overlay.sh: the kernel smoke test runs only zfs-smoke.sh"
	printf 'marker\towner\tarches\tpolicy\ttimeout\treason\n'
	for f in "$M/markers.tsv" "$M/overlay-nextbsd-kernel.tsv"; do
		[ -f "$f" ] || continue
		awk -F"$T" -v OFS="$T" '
			/^#/ || NF < 6 || $1 == "marker" { next }
			$4 == "must-pass" || $4 == "fail-gates" {
				print $1, $2, $3, "warn", $5, "nextbsd-kernel smoke test: not printed by zfs-smoke.sh, the only suite this image runs"
			}' "$f"
	done
	for m in ZFS-KERNEL ZFS-POOL ZFS-DATASET-IO ZFS-EXPORT-IMPORT; do
		printf '%s\tnextbsd-kernel\tboth\tmust-pass\tfail\toptions ZFS: compiled into the kernel, checked on a file-backed pool by ci/zfs-smoke.sh\n' "$m"
	done
} > "$OUT"
n=$(grep -c "${T}must-pass${T}" "$OUT" || true)
[ "$n" -eq 4 ] || { echo "smoke-overlay: expected 4 must-pass rows, got $n" >&2; exit 1; }
echo "smoke-overlay: $(grep -vc '^#' "$OUT") rows in $OUT ($n must-pass)"
